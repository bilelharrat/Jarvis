/** One piece: exact, else the first piece pattern; else as it is. */
function tx(p) {
  const k = String(p).trim().replace(/\s+/g, ' ');
  if (X[k] !== undefined) return X[k];
  const tail = /^(.*?)([:….!?]+)$/.exec(k);
  for (const [re, rep] of PIECES) { if (re.test(k)) return k.replace(re, rep); }
  if (tail && tail[1] && X[tail[1]] !== undefined) return X[tail[1]] + (tail[2] === ':' ? ' :' : tail[2]);
  return k;
}
/** "a · b · c", each piece looked up. */
function dots(v) { return String(v).split(' · ').map((p) => STATUS[p.trim()] || tx(p)).join(' · '); }
/** Several sentences in one string, each looked up. */
function sentences(v) { return String(v).split(/(?<=[.!?])\s+(?=[A-Z“])/).map(tx).join(' '); }
/** "Sonnet 4.5 at High effort" (compare.js strongerButton). */
function stronger(w) { const m = new RegExp(`^(.+) at ${EFF_RE} effort$`).exec(w); return m ? `${m[1]} en effort ${EFF_LOW[m[2]]}` : w; }

