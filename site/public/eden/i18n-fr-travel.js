// a packing item's reason (travel-plan-rules.js packingList): counts, forecasts, the stop it comes from
function why(w) {
  let more = '';
  const m = / \(and (\d+) more (day|stop)s?\)$/.exec(w);
  if (m) { w = w.slice(0, m.index); more = ` (et ${m[1]} ${m[2] === 'day' ? 'jour' : 'étape'}${s(m[1])} de plus)`; }
  const out = w
    .replace(/^every trip$/, 'pour tout voyage')
    .replace(/^(\d+) days?, (\d+) nights?$/, (x, a, b) => `${a} jour${s(a)}, ${b} nuit${s(b)}`)
    .replace(/^(\d+) nights?$/, (x, a) => `${a} nuit${s(a)}`)
    .replace(/^(\d+) travellers$/, '$1 voyageurs')
    .replace(new RegExp(`^(\\d+)% rain forecast (${D}) · (.+)$`), (x, p, d, src) => `${p} % de pluie prévus le ${fd(d)} · ${src}`)
    .replace(new RegExp(`^(high|low) of (-?\\d+)° forecast (${D}) · (.+)$`), (x, k, t, d, src) => `${k === 'high' ? 'maximale' : 'minimale'} de ${t}° prévue le ${fd(d)} · ${src}`)
    .replace(/^(?:(flight|car hire): )?“(.+)”, Day (\d+)$/, (x, k, n, d) => `${k ? `${k === 'flight' ? 'vol' : 'location de voiture'} : ` : ''}« ${n} », jour ${d}`);
  return out + more;
}
