/** sheet-model describeDiff(): "12 cells on “Sales” · new sheet “Pivot” · 1 chart". */
function frDiff(s) {
  if (s === 'no changes') return 'aucune modification';
  return s.split(' · ').map((p) => {
    let m;
    if ((m = /^([\d,]+) cells?(?: on (\d+) sheets| on (“.+”))?$/.exec(p))) return `${frNum(m[1])} ${one(m[1]) ? 'cellule' : 'cellules'}${m[2] ? ` sur ${m[2]} feuilles` : m[3] ? ` sur ${m[3]}` : ''}`;
    if ((m = /^new sheet(s?) (.+)$/.exec(p))) return `${m[1] ? 'nouvelles feuilles' : 'nouvelle feuille'} ${m[2]}`;
    if ((m = /^removes (.+)$/.exec(p))) return `supprime ${m[1]}`;
    if (/^renames /.test(p)) return p.replace(/renames (“.*?”) to (“.*?”)/g, 'renomme $1 en $2');
    if ((m = /^(\d+) charts?$/.exec(p))) return `${m[1]} ${one(m[1]) ? 'graphique' : 'graphiques'}`;
    return p;
  }).join(' · ');
}
