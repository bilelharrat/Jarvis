const NO_LOCAL = `Activez Ollama ou LM${NBSP}Studio pour utiliser le mode confidentiel.`;
const reason = (r) => {
  const s = String(r);
  if (s === 'Turn on Ollama or LM Studio to use privacy mode.') return NO_LOCAL;
  if (s === 'Privacy mode needs your Mac, through its link to askeden.com.') return 'Le mode confidentiel a besoin de votre Mac, via son lien avec askeden.com.';
  if (s === 'Checking…') return 'Vérification…';
  let m = /^(.+)\. Load one \(e\.g\. ollama pull llama3\.2\), then try again\.$/.exec(s);
  if (m) return `${reason(m[1])}. Chargez-en un (p.${NBSP}ex. ollama pull llama3.2), puis réessayez.`;
  m = /^(.+) is running but has no chat model loaded$/.exec(s); if (m) return `${m[1]} est lancé mais aucun modèle de discussion n’est chargé`;
  m = /^(.+) isn’t running$/.exec(s); if (m) return `${m[1]} n’est pas lancé`;
  m = /^(.+) didn’t answer in time$/.exec(s); if (m) return `${m[1]} n’a pas répondu à temps`;
  m = /^(.+) answered HTTP (\d+)$/.exec(s); if (m) return `${m[1]} a répondu HTTP ${m[2]}`;
  m = /^(.+) sent an unreadable model list$/.exec(s); if (m) return `${m[1]} a envoyé une liste de modèles illisible`;
  return s;
};

