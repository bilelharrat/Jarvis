// The try-it tour's chapters and steps (ROADMAP I1). Each step says what a feature does, asks
// the person to do it, and check()s that they did, from the page itself: an element that
// appeared, a class, a setting that changed, or an event (tour-model.js detector: c.saw,
// c.has, c.count, c.state…). start(a) sets the scene with tour.js's helpers (a new chat, the
// inspector open); base(c) measures what "before" looked like. Plain data and functions, no
// imports and no DOM globals, so the tests run every check against a fake page.
//
// Fields: id, chapter, title, body (what it does), tryIt (what to do), target (selectors,
// the first one on screen gets the spotlight), side (lives in the sidebar: on a phone, the
// menu button first), needs ('mac' | 'account': where it isn't available for real, the step
// says so and this practice version stands in), sample ('composer' | 'compose': offer a sample
// file), simulate ('dictate' | 'talk': the microphone stays off in practice), noScroll (the tour
// doesn't scroll the target into view), seconds (for the chapter's time), done (the line shown
// with the check).

