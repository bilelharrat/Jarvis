/** "3 pm" / "10:30am" → "15 h" / "10 h 30". */
function frTime(h, m, ap) {
  let H = Number(h) % 12;
  if (/p/i.test(ap)) H += 12;
  return m && m !== '00' ? `${H}${NB}h${NB}${m}` : `${H}${NB}h`;
}
/** English dates and times (en-US, as mail-plan.js and mail-check.js write them) inside a string, in French. */
function frDates(s) {
  return String(s)
    .replace(/\b(January|February|March|April|May|June|July|August|September|October|November|December) (\d{1,2}), (\d{4})\b/g, (_, mo, d, y) => `${d} ${MONTH[mo]} ${y}`)
    .replace(new RegExp(`\\b${MON_RE}\\.? (\\d{1,2})\\b`, 'g'), (x, mo, d) => `${d} ${MONTH[x.split(' ')[0].replace('.', '')] || MON_ABBR[mo]}`)
    .replace(/\b(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday),? /g, (_, w) => `${WEEKDAY[w]} `)
    .replace(/\b(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday)\b/g, (w) => WEEKDAY[w])
    .replace(/\b(Mon|Tue|Wed|Thu|Fri|Sat|Sun),? /g, (_, w) => `${WD_ABBR[w]} `)
    .replace(/\b(\d{1,2})(?::(\d{2}))?\s?(am|pm)\b/gi, (_, h, m, ap) => frTime(h, m, ap));
}

