/** mail-rules.js describeRule: "Archive receipts, invoices and orders from stripe.com, once you’ve seen them." */
function frRule(_, act, days, ask, what, mid, when) {
  const a = act === 'Archive' ? 'Archiver' : act === 'Mark read' ? 'Marquer comme lu' : act === 'Star' ? 'Ajouter une étoile'
    : days ? `Mettre en attente ${days}${NB}${plural(days, 'jour', 'jours')}` : ask !== undefined ? `Préparer une réponse (${ask}) à relire` : 'Vous prévenir';
  const m = String(mid || '')
    .replace(/^ from (.*?)(?=( with “| mentioning “|$))/, (x, f) => ` de ${f.split(' or ').join(' ou ')}`)
    .replace(/ with “(.*)” in the subject/, (x, w) => ` avec ${quoteList(w)} dans l’objet`)
    .replace(/ mentioning “(.*)”/, (x, w) => ` mentionnant ${quoteList(w)}`);
  const w = when === ', once you’ve seen them' ? ', une fois lus' : when === ', while unread' ? ', tant qu’ils sont non lus' : '';
  return `${a}${NB}: ${RULE_KIND[what] || what}${m}${w}.`;
}

