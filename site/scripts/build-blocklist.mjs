// The cloud browser's ad and tracker blocklist (src/browser/blocklist.js), made from the same
// filter lists J.A.R.V.I.S.'s own browser uses (Ghostery's adblocker: EasyList, EasyPrivacy,
// Peter Lowe's list and uBlock Origin's lists). The cloud browser blocks by host: every
// request whose host, or a parent of it, is on the list is refused before it leaves the
// browser. Only whole-host rules are taken (`||host^`, with no options or only type and
// party ones); exceptions (`@@||host^`) take a host back off. Run it to refresh the list:
//
//   node scripts/build-blocklist.mjs

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PREFIX = 'https://raw.githubusercontent.com/ghostery/adblocker/master/packages/adblocker/assets';
export const LISTS = [
  'easylist/easylist.txt', 'easylist/easyprivacy.txt', 'peter-lowe/serverlist.txt',
  'ublock-origin/badware.txt', 'ublock-origin/filters.txt', 'ublock-origin/privacy.txt',
  'ublock-origin/resource-abuse.txt', 'ublock-origin/quick-fixes.txt', 'ublock-origin/unbreak.txt',
].map((p) => `${PREFIX}/${p}`);

const TYPE_OPTS = /^(~?(third-party|3p|first-party|1p|script|image|stylesheet|css|xmlhttprequest|xhr|subdocument|frame|ping|media|font|object|other|websocket|popup|all|important|doc|document))$/;
const HOST = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/;

/** The hosts a filter list blocks outright, and those it takes back. */
export function hostsOf(text) {
  const block = new Set();
  const allow = new Set();
  for (const raw of text.split('\n')) {
    const line = raw.trim().toLowerCase();
    const m = /^(@@)?\|\|([a-z0-9.-]+)\^(\$(.*))?$/.exec(line);
    if (!m || !HOST.test(m[2])) continue;
    if (m[4] && !m[4].split(',').every((o) => TYPE_OPTS.test(o))) continue;
    (m[1] ? allow : block).add(m[2]);
  }
  // Peter Lowe's list in hosts-file form: "127.0.0.1 host"
  for (const raw of text.split('\n')) {
    const m = /^(?:127\.0\.0\.1|0\.0\.0\.0)\s+([a-z0-9.-]+)\s*$/i.exec(raw.trim());
    if (m && HOST.test(m[1].toLowerCase()) && m[1] !== 'localhost') block.add(m[1].toLowerCase());
  }
  return { block, allow };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const all = new Set();
  const back = new Set();
  for (const url of LISTS) {
    const r = await fetch(url);
    if (!r.ok) throw new Error(`${url}: ${r.status}`);
    const { block, allow } = hostsOf(await r.text());
    block.forEach((h) => all.add(h));
    allow.forEach((h) => back.add(h));
  }
  back.forEach((h) => all.delete(h));
  // A host under a blocked parent adds nothing.
  const hosts = [...all].filter((h) => { const p = h.split('.'); for (let i = 1; i < p.length - 1; i++) if (all.has(p.slice(i).join('.'))) return false; return true; }).sort();
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'browser', 'blocklist.js');
  writeFileSync(out, `// GENERATED by scripts/build-blocklist.mjs on ${new Date().toISOString().slice(0, 10)} (${hosts.length} hosts): run it again, don't edit this.\nexport const BLOCKED_HOSTS = ${JSON.stringify(hosts.join('\n'))};\n`);
  console.log(`wrote ${out}: ${hosts.length} hosts`);
}
