// The preview of askeden.com at preview.askeden.com: wrangler.preview.toml, made from
// wrangler.toml so the two never drift apart. It is a separate Worker (`eden-preview`) with
// its own Durable Objects (its own, empty accounts), its own rate-limit counters and no R2
// bucket, so nothing in it can reach the live site's data. Its secrets are its own too:
//
//   node scripts/preview-config.mjs
//   npx wrangler secret put ANTHROPIC_API_KEY -c wrangler.preview.toml   (and the others it needs)
//   npx wrangler deploy -c wrangler.preview.toml
//
// Sign in with Apple has https://preview.askeden.com/api/web/apple/callback as a return URL
// (Services ID com.askeden.eden.web); Google needs …/api/web/google/callback and
// …/api/chat/google/callback added.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', 'wrangler.toml');
const target = join(here, '..', 'wrangler.preview.toml');

export function previewConfig(text) {
  let out = text;
  const swap = (pattern, replacement, what) => {
    if (!pattern.test(out)) throw new Error(`wrangler.toml changed: no ${what} to replace`);
    out = out.replace(pattern, replacement);
  };
  swap(/^name = "jarvis-download"$/m, 'name = "eden-preview"', 'name');
  swap(/^routes = \[[\s\S]*?^\]$/m, 'routes = [\n  { pattern = "preview.askeden.com", custom_domain = true },\n]', 'routes');
  // Rate limits count per namespace across the account: the preview gets its own (10NN → 20NN).
  swap(/namespace_id = "10(\d\d)"/g, 'namespace_id = "20$1"', 'rate-limit namespaces');
  // Sign-ups: open on the preview, Turnstile or not (live stays as wrangler.toml says, fail-closed).
  swap(/^SIGNUPS = "[a-z]*"$/m, 'SIGNUPS = "open"\nTURNSTILE_OPTIONAL = "1"', 'SIGNUPS');
  // No R2: the preview never reads or writes the live downloads bucket (it is last in the file).
  swap(/\n# Keep the R2 bucket last[\s\S]*$/, '\n', 'R2 bucket');
  if (/r2_buckets|jarvis-download"|askeden\.com\/\*/.test(out)) throw new Error('the preview config still points at the live site');
  return `# GENERATED by scripts/preview-config.mjs from wrangler.toml: edit that, not this.\n${out}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(target, previewConfig(readFileSync(source, 'utf8')));
  console.log(`wrote ${target}`);
}
